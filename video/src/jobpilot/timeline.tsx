import type { ReactNode } from "react";
import { Audio, interpolate, staticFile } from "remotion";
import { TransitionSeries, linearTiming } from "@remotion/transitions";
import { fade } from "@remotion/transitions/fade";
import clipConfig from "./clips.json";

export const FPS = 30;
const TRANSITION = 15;

// `voice` scenes carry the interview audio, so the music ducks under them.
export type Scene = { frames: number; node: ReactNode; voice?: boolean };

/** Length of a VAPI interview highlight from clips.json. */
export const clipFrames = (name: string) => {
  const clip = clipConfig.clips.find((c) => c.name === name)!;
  return Math.round((clip.to - clip.from) * FPS);
};

export const timelineDuration = (scenes: Scene[]) =>
  scenes.reduce((sum, s) => sum + s.frames, 0) - TRANSITION * (scenes.length - 1);

const MUSIC_VOLUME = 0.32;
const DUCKED_VOLUME = 0.06;
const DUCK_RAMP = 15;

function musicVolume(scenes: Scene[], frame: number) {
  const duration = timelineDuration(scenes);
  // Timeline ranges of the voice scenes (scenes overlap by TRANSITION frames).
  const voiceRanges = scenes.flatMap((scene, i) => {
    const start = scenes.slice(0, i).reduce((sum, s) => sum + s.frames, 0) - TRANSITION * i;
    return scene.voice ? [[start, start + scene.frames] as const] : [];
  });
  let duck = 0;
  for (const [start, end] of voiceRanges) {
    duck = Math.max(
      duck,
      interpolate(frame, [start - DUCK_RAMP, start, end - DUCK_RAMP, end], [0, 1, 1, 0], {
        extrapolateLeft: "clamp",
        extrapolateRight: "clamp",
      }),
    );
  }
  const fadeOut = interpolate(frame, [duration - 60, duration], [1, 0], {
    extrapolateLeft: "clamp",
    extrapolateRight: "clamp",
  });
  return interpolate(duck, [0, 1], [MUSIC_VOLUME, DUCKED_VOLUME]) * fadeOut;
}

/** Scenes joined by short fades, over a music track that ducks under voice scenes. */
export function Timeline({ scenes, music }: { scenes: Scene[]; music: string }) {
  return (
    <>
      {/* Original track generated by scripts/make-music.mjs */}
      <Audio src={staticFile(music)} volume={(f) => musicVolume(scenes, f)} />
      <TransitionSeries>
        {scenes.flatMap((scene, i) => [
          ...(i > 0
            ? [<TransitionSeries.Transition key={`t${i}`} presentation={fade()} timing={linearTiming({ durationInFrames: TRANSITION })} />]
            : []),
          <TransitionSeries.Sequence key={`s${i}`} durationInFrames={scene.frames}>
            {scene.node}
          </TransitionSeries.Sequence>,
        ])}
      </TransitionSeries>
    </>
  );
}
